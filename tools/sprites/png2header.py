# Embeds the sprites and sounds in native/assets into the DLL: writes a header per file into native/src
# (<name>_png.h, <name>_wav.h).
# Usage (from the repository root): python tools/sprites/png2header.py
from pathlib import Path

ASSETS = [
    ('coop_button.png', 'kCoopButtonPng', 'The main menu COOP button: 2 frames of 98x26 side by side (with and without the word).'),
    ('coop_ui.png', 'kCoopUiPng', 'Blank button bodies for the COOP screen: 4 frames of 89x26 (green, purple, grey, pink).'),
    ('coop_fx.png', 'kCoopFxPng', "The players' effects: 2 frames of 9x9 (a star, a music note); tools/sprites/make_fx.py."),
    ('bonk.wav', 'kBonkWav', 'The bonk of a pickaxe on another player: 16-bit mono PCM WAV.'),
    ('dance.wav', 'kDanceWav', "The dance's music loop: 16-bit mono PCM WAV; tools/sprites/make_dance_music.py."),
]

for file, symbol, about in ASSETS:
    data = Path(f'native/assets/{file}').read_bytes()
    stem, ext = file.rsplit('.', 1)
    rows = [', '.join(f'0x{b:02X}' for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    Path(f'native/src/{stem}_{ext}.h').write_text(
        f'// Generated by tools/sprites/png2header.py from native/assets/{file} - do not edit.\n'
        f'// {about}\n'
        '#pragma once\n\n'
        'namespace coop {\n\n'
        f'constexpr unsigned char {symbol}[] = {{\n    ' + ',\n    '.join(rows) + ',\n};\n\n'
        '}  // namespace coop\n', newline='\n')
    print(f'{file}: {len(data)} bytes')
