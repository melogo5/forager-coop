# Embeds the sprites in native/assets into the DLL: writes a header per PNG into native/src.
# Usage (from the repository root): python tools/sprites/png2header.py
from pathlib import Path

ASSETS = [
    ('coop_button', 'kCoopButtonPng', 'The main menu COOP button: 2 frames of 98x26 side by side (with and without the word).'),
    ('coop_ui', 'kCoopUiPng', 'Blank button bodies for the COOP screen: 4 frames of 89x26 (green, purple, grey, pink).'),
]

for name, symbol, about in ASSETS:
    data = Path(f'native/assets/{name}.png').read_bytes()
    rows = [', '.join(f'0x{b:02X}' for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    Path(f'native/src/{name}_png.h').write_text(
        f'// Generated by tools/sprites/png2header.py from native/assets/{name}.png - do not edit.\n'
        f'// {about}\n'
        '#pragma once\n\n'
        'namespace coop {\n\n'
        f'constexpr unsigned char {symbol}[] = {{\n    ' + ',\n    '.join(rows) + ',\n};\n\n'
        '}  // namespace coop\n', newline='\n')
    print(f'{name}: {len(data)} bytes')
