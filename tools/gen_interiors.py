# Turns the room dump (decompiled/data/rooms_interiors.txt, made by decompiled/tools/DumpRooms.csx) into the C++
# plans interiors.cpp builds the interiors from: native/src/interior_plans.inc.
# Usage: python tools/gen_interiors.py
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
dump = (root / 'decompiled/data/rooms_interiors.txt').read_text(encoding='utf-8').splitlines()
objects = {}
for line in (root / 'decompiled/data/objects.tsv').read_text(encoding='utf-8').splitlines()[1:]:
    cols = line.split('\t')
    objects[cols[1]] = int(cols[0])
sprites = {}
for line in (root / 'decompiled/data/sprites.tsv').read_text(encoding='utf-8').splitlines():
    cols = line.split('\t')
    if len(cols) > 1 and cols[0].isdigit():
        sprites[cols[1]] = int(cols[0])


# Instance creation code (gml_RoomCC_<room>_<n>_Create): YYC keeps none in data.win, so the dump cannot say which
# instance has some. These objects have it, the n-th of them in room order getting code n (checked for the museum:
# each showcase's code sets `owner` to the bundle next to it). The wizard tower's one code (the dungeon entry's
# secretRoom) is left out: dungeons are off in coop.
creation_objects = {'rmMuseum': ('objMuseumBundle', 'objMuseumShowcase')}
creation_code = {}
for line in (root / 'decompiled/data/room_creation_code.tsv').read_text(encoding='utf-8').splitlines():
    m = re.match(r'gml_RoomCC_(\w+?)_(\d+)_Create\t(0x[0-9A-F]+)', line)
    if m:
        creation_code.setdefault(m[1], {})[int(m[2])] = m[3]


def pair(text):  # "(1,25, 6)" -> (1.25, 6.0): the dump writes decimal commas
    a, b = text.strip('()').split(', ')
    return float(a.replace(',', '.')), float(b.replace(',', '.'))


def colour(argb):  # FF2B2938 (A, B, G, R as the dump prints a GM colour) -> 0x2B2938
    return int(argb[2:], 16)


rooms = []
room = None
depth = 0
for line in dump:
    if line.startswith('room '):
        m = re.match(r'room (\d+) (\S+) (\d+)x(\d+)', line)
        room = {'index': int(m[1]), 'name': m[2], 'width': int(m[3]), 'height': int(m[4]), 'spawn': None,
                'instances': [], 'coded': 0, 'tiles': [], 'pictures': [], 'backgrounds': []}
        rooms.append(room)
        continue
    m = re.match(r"  layer '(.*)' depth (-?\d+) type (\w+)", line)
    if m:
        depth = int(m[2])
        continue
    m = re.match(r'    instance (\w+) at (\(.*?\)) scale (\(.*?\)).* id (\d+)$', line)
    if m:
        x, y = pair(m[2])
        sx, sy = pair(m[3])
        if m[1] == 'objPlayer':
            room['spawn'] = (x, y)
        else:
            code = '0'
            if m[1] in creation_objects.get(room['name'], ()):
                code = creation_code[room['name']][room['coded']]
                room['coded'] += 1
            room['instances'].append((objects[m[1]], m[1], x, y, sx, sy, int(m[4]), code))
        continue
    m = re.match(r'    tiles: tileset (\d+) (\w+) tile (\d+)x(\d+) .*; (\d+)x(\d+) cells', line)
    if m:
        room['tiles'].append({'depth': depth, 'tileset': int(m[1]), 'name': m[2], 'cols': int(m[5]),
                              'rows': int(m[6]), 'cells': []})
        continue
    m = re.match(r'    row (.*)', line)
    if m:
        room['tiles'][-1]['cells'].extend(int(v) for v in m[1].split())
        continue
    m = re.match(r'    background: sprite (\S+) colour (\w+) tiled (\w+)/(\w+)', line)
    if m:
        sprite = -1 if m[1] == '-' else sprites[m[1]]
        room['backgrounds'].append((depth, sprite, colour(m[2]), m[3] == 'True', m[4] == 'True'))
        continue
    m = re.match(r'    sprite (\w+) at (\(.*?\))', line)
    if m:
        x, y = pair(m[2])
        room['pictures'].append((depth, sprites[m[1]], m[1], x, y))

out = ['// Generated by tools/gen_interiors.py from decompiled/data/rooms_interiors.txt - do not edit.', '']
for r in rooms:
    assert r['spawn'] is not None, r['name']
    for t in r['tiles']:
        assert len(t['cells']) == t['cols'] * t['rows'], (r['name'], t['name'])
        out.append(f"const uint16_t k{r['name']}Tiles{t['depth']}[] = {{")
        for i in range(0, len(t['cells']), 26):
            out.append('    ' + ', '.join(str(c) for c in t['cells'][i:i + 26]) + ',')
        out.append('};')
    out.append(f"const Plan k{r['name']}{{{r['index']}, {r['width']}, {r['height']}, {r['spawn'][0]:g}, {r['spawn'][1]:g},")
    out.append('    {' + ', '.join(f'{{{d}, {s}, {c:#08x}, {str(h).lower()}, {str(v).lower()}}}' for d, s, c, h, v in r['backgrounds']) + '},')
    out.append('    {' + ', '.join(f'{{{d}, {s}, {x:g}, {y:g}}}' for d, s, _, x, y in r['pictures']) + '},')
    out.append('    {' + ', '.join(f"{{{t['depth']}, {t['tileset']}, {t['cols']}, {t['rows']}, k{r['name']}Tiles{t['depth']}}}" for t in r['tiles']) + '},')
    out.append('    {')
    assert r['coded'] == len(creation_code.get(r['name'], {})) or r['name'] not in creation_objects, r['name']
    for o, name, x, y, sx, sy, room_id, code in r['instances']:
        out.append(f'        {{{o}, {x:g}, {y:g}, {sx:g}, {sy:g}, {room_id}, {code}}},  // {name}')
    out.append('    }};')
    out.append('')
out.append('const Plan* const kPlans[] = {' + ', '.join(f"&k{r['name']}" for r in rooms) + '};')
(root / 'native/src/interior_plans.inc').write_text('\n'.join(out) + '\n', encoding='utf-8')
print(f"{len(rooms)} rooms: " + ', '.join(f"{r['name']} ({len(r['instances'])} objects, {len(r['tiles'])} tile layers)" for r in rooms))
